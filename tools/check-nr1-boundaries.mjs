// NEXTREP 1.0 (N0) — architecture boundaries of the new app in src/nr1/.
//
// The new app must stay independent of the old one (src/app/, frozen until N12, decision C01-7):
//   * its REAL dependency graph (esbuild metafile of the bundle) may contain only src/nr1/**, the
//     approved pure modules of src/engine/, the build-time atlas release module and an allowlist of
//     npm packages — no src/app/, no legacy engine adapters, no Supabase client;
//   * the produced bundle must not contain the old data model (localStorage keys, legacy ids, the
//     old exercise ids), any Supabase address or key, the protected projects, storage APIs that
//     could read old data, or CDN URLs.
//
// Used two ways:
//   1. by tools/build-nr1.mjs, before anything is written (a violation fails the build);
//   2. as a CLI that re-checks a finished build:
//        node tools/check-nr1-boundaries.mjs [--dist dist-nr1] [--work .build-nr1]
//      (CI runs it as its own step).
import { readFileSync, existsSync } from "node:fs";
import { dirname, resolve, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// Existing Supabase projects that NEXTREP 1.0 must never reach (decision N0-D). Their configuration
// is not touched; the refs are listed here only so that they can be refused.
export const PROTECTED_SUPABASE_REFS = {
  pyhhvbqcjhpulrmqiguz: "produkcja",
  qnyjrvoudyjxvitazclo: "nextrep-f5-test",
};

// Virtual module with the atlas release metadata generated by the build (decision C01-4).
export const ATLAS_RELEASE_MODULE = "nr1:atlas-release";

// Pure modules of src/engine/ that NEXTREP 1.0 may use. legacy-progression.js, load-legacy-map.js,
// volume.js and index.js (which re-exports them) serve only the old app.
export const ALLOWED_ENGINE_MODULES = ["rir.js", "load.js", "cardio.js", "atlas-schema.js", "atlas-validate.js", "load-snapshot.js", "hierarchy.js", "muscle-stats.js", "cardio-stats.js"]; // AT3.2b: muscle-stats.js replaces muscle-work.js (AT3-D17); AT3.2c: cardio.js, cardio-stats.js
export const FORBIDDEN_ENGINE_MODULES = ["legacy-progression.js", "load-legacy-map.js", "volume.js", "index.js"];

// npm packages allowed in the bundle. A new runtime dependency needs approval (C01-6) and an entry here.
export const ALLOWED_PACKAGES = ["react", "react-dom", "scheduler"];

const toPosix = (p) => p.split(sep).join("/");
const rel = (abs) => toPosix(relative(ROOT, abs));

// ---- 1. dependency rules (applied while resolving AND to the final metafile) --------------------
// Returns a reason (string) when a resolved file is not allowed in NEXTREP 1.0, otherwise null.
export function forbiddenPathReason(absPath) {
  const p = rel(absPath);
  if (p.startsWith("src/app/")) return "stara aplikacja (src/app/)";
  if (p === "index.html") return "powłoka starej aplikacji (index.html)";
  if (p.startsWith("tools/")) return "narzędzia buildu (tools/) nie są częścią aplikacji";
  if (p.startsWith("db/") || p.startsWith("docs/")) return "pliki SQL / dokumentacja (stary model danych i migracje)";
  if (p.startsWith("android/")) return "projekt Android starej aplikacji (android/)";
  if (p.startsWith("src/engine/")) {
    const f = p.slice("src/engine/".length);
    if (FORBIDDEN_ENGINE_MODULES.includes(f)) return `moduł silnika tylko dla starej aplikacji (src/engine/${f})`;
    if (!ALLOWED_ENGINE_MODULES.includes(f)) return `moduł silnika spoza listy dozwolonych (src/engine/${f})`;
  }
  const pkg = packageOf(p);
  if (pkg && pkg.startsWith("@supabase/")) return `klient Supabase (${pkg})`;
  if (pkg && !ALLOWED_PACKAGES.includes(pkg)) return `pakiet npm spoza listy dozwolonych (${pkg})`;
  return null;
}

function packageOf(p) {
  const i = p.lastIndexOf("node_modules/");
  if (i < 0) return null;
  const parts = p.slice(i + "node_modules/".length).split("/");
  return parts[0].startsWith("@") ? `${parts[0]}/${parts[1]}` : parts[0];
}

// Every input of the bundle must be: the entry, a file of src/nr1/, an allowed engine module, an
// allowed package, or the virtual atlas release module.
export function checkMetafile(metafile, { entry, entries = [] }) {
  const violations = [];
  const entryRels = new Set([entry, ...entries].filter(Boolean).map((e) => rel(resolve(ROOT, e))));
  for (const input of Object.keys(metafile.inputs || {})) {
    if (input.startsWith(`${ATLAS_RELEASE_MODULE.split(":")[0]}:`)) continue; // virtual namespace
    const abs = resolve(ROOT, input);
    const p = rel(abs);
    const reason = forbiddenPathReason(abs);
    if (reason) { violations.push({ rule: "DEPENDENCY", file: p, message: `Niedozwolona zależność: ${reason}` }); continue; }
    const ok = entryRels.has(p) || p.startsWith("src/nr1/") || p.startsWith("src/engine/") || packageOf(p);
    if (!ok) violations.push({ rule: "DEPENDENCY", file: p, message: "Plik spoza src/nr1/, dozwolonego silnika i dozwolonych pakietów" });
  }
  return violations;
}

// ---- 2. bundle content rules ------------------------------------------------------------------
// Ids of the 68 exercises of the old atlas (DEFAULT_EXERCISES). NEXTREP 1.0 does not keep any
// compatibility with them. Ids that the 1.0 atlas itself issues are not treated as old.
export function oldExerciseIds(atlas) {
  const src = readFileSync(resolve(ROOT, "src/app/10-atlas-templates.jsx"), "utf8"); // read only
  const start = src.indexOf("const DEFAULT_EXERCISES = [");
  const end = src.indexOf("\n];", start);
  if (start < 0 || end < 0) throw new Error("check-nr1-boundaries: DEFAULT_EXERCISES not found in the old app");
  const ids = [...src.slice(start, end).matchAll(/\{ id: "([a-z0-9_]+)"/g)].map((m) => m[1]);
  const issued = new Set([...(atlas?.issuedIds || []), ...((atlas?.exercises || []).map((e) => e && e.exerciseId))]);
  return ids.filter((id) => !issued.has(id));
}

export function bundlePatterns({ atlas } = {}) {
  const patterns = [
    { rule: "SUPABASE", re: /supabase\.(?:co|in|com)\b/i, message: "adres Supabase" },
    { rule: "SUPABASE", re: /sb_(?:publishable|secret)_/, message: "klucz Supabase" },
    { rule: "SUPABASE", re: /@supabase\//, message: "klient Supabase" },
    ...Object.entries(PROTECTED_SUPABASE_REFS).map(([ref, name]) => ({ rule: "PROTECTED_PROJECT", re: new RegExp(ref), message: `projekt chroniony: ${name}` })),
    { rule: "OLD_DATA", re: /trainapp_/, message: "klucze danych starej aplikacji (trainapp_*)" },
    { rule: "OLD_DATA", re: /nextrep_[a-z0-9]/, message: "klucze starej aplikacji (nextrep_*)" },
    { rule: "OLD_DATA", re: /legacy_id/, message: "stary model synchronizacji (legacy_id)" },
    { rule: "OLD_DATA", re: /\buser_data\b/, message: "stara tabela user_data" },
    { rule: "OLD_STORAGE", re: /\blocalStorage\b/, message: "localStorage (dane starej aplikacji)" },
    { rule: "OLD_STORAGE", re: /\bsessionStorage\b/, message: "sessionStorage" },
    { rule: "CDN", re: /https:\/\/(?:esm\.sh|unpkg\.com|cdn\.tailwindcss\.com|fonts\.googleapis\.com|fonts\.gstatic\.com|cdn\.jsdelivr\.net|cdnjs\.cloudflare\.com)/, message: "adres CDN" },
  ];
  const old = oldExerciseIds(atlas);
  if (old.length) {
    const alt = old.map((id) => id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|");
    patterns.push({ rule: "OLD_EXERCISE_ID", re: new RegExp(`["'\`](?:${alt})["'\`]`), message: "identyfikator ćwiczenia starego atlasu" });
  }
  return patterns;
}

export function checkBundleText(text, opts = {}) {
  const violations = [];
  for (const { rule, re, message } of bundlePatterns(opts)) {
    const m = re.exec(text);
    if (m) violations.push({ rule, file: opts.file || "bundle", message: `W bundlu: ${message} („${m[0]}”)` });
  }
  return violations;
}

export function formatViolations(violations) {
  return violations.map((v) => `  ✗ [${v.rule}] ${v.file}: ${v.message}`).join("\n");
}

// ---- CLI ---------------------------------------------------------------------------------------
const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const arg = (name, def) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : def; };
  const dist = resolve(ROOT, arg("--dist", "dist-nr1"));
  const work = resolve(ROOT, arg("--work", ".build-nr1"));
  const metaPath = resolve(work, "metafile.json");
  const infoPath = resolve(work, "build-info.json");
  const appPath = resolve(dist, "assets/app.js");
  for (const f of [metaPath, infoPath, appPath, resolve(dist, "index.html")]) {
    if (!existsSync(f)) { console.error(`[check-nr1] brak ${rel(f)} — najpierw: node tools/build-nr1.mjs`); process.exit(1); }
  }
  const info = JSON.parse(readFileSync(infoPath, "utf8"));
  const atlas = JSON.parse(readFileSync(resolve(ROOT, info.atlasPath), "utf8"));
  const modulesMetaPath = resolve(work, "metafile-modules.json");
  if (!existsSync(modulesMetaPath)) { console.error(`[check-nr1] brak ${rel(modulesMetaPath)} — najpierw: node tools/build-nr1.mjs`); process.exit(1); }
  const violations = [
    ...checkMetafile(JSON.parse(readFileSync(metaPath, "utf8")), { entry: info.entry }),
    ...checkMetafile(JSON.parse(readFileSync(modulesMetaPath, "utf8")), { entries: info.modules || [] }),
    ...checkBundleText(readFileSync(appPath, "utf8"), { atlas, file: rel(appPath) }),
    ...checkBundleText(readFileSync(resolve(dist, "index.html"), "utf8"), { atlas, file: rel(resolve(dist, "index.html")) }),
  ];
  if (violations.length) {
    console.error(`[check-nr1] naruszenia granic NEXTREP 1.0 (${violations.length}):\n${formatViolations(violations)}`);
    process.exit(1);
  }
  const inputs = Object.keys(JSON.parse(readFileSync(metaPath, "utf8")).inputs).length;
  const modules = (info.modules || []).length;
  console.log(`[check-nr1] OK — ${inputs} plików w grafie zależności aplikacji, ${modules} modułów src/nr1/ sprawdzonych osobno, bundel bez niedozwolonych zależności, danych starej aplikacji i konfiguracji backendu`);
}
